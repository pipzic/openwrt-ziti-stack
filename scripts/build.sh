#!/usr/bin/env bash
# Build the stack packages for one OpenWrt release into /out/<release>/<arch>/.
#   build.sh <release>
set -euo pipefail

release="${1:?usage: build.sh <release>}"
# shellcheck source=scripts/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

OUT_DIR="${OUT_DIR:-/out}"
CACHE_DIR="${CACHE_DIR:-/tmp/openwrt-ziti-cache}"
BUILD_JOBS="${BUILD_JOBS:-$(nproc)}"
# The SDK's prerequisite check refuses restrictive umasks.
umask 022

# The SDK turns every setting of the release build into an unconditional Kconfig
# default in Config-build.in. PACKAGE_* defaults therefore win again for hidden
# symbols even when .config says "not set", and the build would compile the whole
# release package set. Remove only that package selection. kmod-tun stays: its
# symbol is not regenerated by a package scan, and the firmware supplies it at
# runtime. Target, toolchain and libc defaults remain untouched.
strip_sdk_release_package_snapshot() {
  local input="Config-build.in" output="Config-build.in.minimal" remaining
  grep -q '^config PACKAGE_' "$input" || die "SDK Config-build.in has no PACKAGE_* entries"

  awk '
    FNR == NR {
      if ($1 == "config" && $2 ~ /^PACKAGE_/) {
        package[substr($2, 9)] = 1
      }
      if ($1 == "config" && $2 ~ /^MODULE_DEFAULT_/) {
        module_default[substr($2, 16)] = 1
      }
      next
    }

    /^config / {
      symbol = $2
      skip = (symbol ~ /^PACKAGE_/ && symbol != "PACKAGE_kmod-tun") ||
             (symbol ~ /^TARGET_DEVICE_/) ||
             (symbol == "BUILDBOT") ||
             (symbol == "TARGET_MULTI_PROFILE") ||
             (symbol == "TARGET_ALL_PROFILES") ||
             (symbol == "TARGET_PER_DEVICE_ROOTFS") ||
             (symbol ~ /^DEFAULT_/ &&
               ((substr(symbol, 9) in package) ||
                (substr(symbol, 9) in module_default))) ||
             (symbol ~ /^MODULE_DEFAULT_/)
    }

    skip {
      if (/^[[:space:]]*$/) {
        skip = 0
      }
      next
    }

    { print }
  ' "$input" "$input" > "$output"

  remaining="$(sed -nE 's/^config (PACKAGE_[^[:space:]]+)$/\1/p' "$output")"
  [[ "$remaining" == 'PACKAGE_kmod-tun' ]] \
    && ! grep -Eq '^config (TARGET_DEVICE_|MODULE_DEFAULT_)' "$output" \
    || die "failed to remove the SDK release package snapshot"
  mv "$output" "$input"
}

# Print the single file matching a package name, or fail.
find_package() {
  local matches
  matches="$(find "$SDK_DIR/bin/packages" -type f -name "$1" -print)"
  [[ "$(printf '%s' "$matches" | grep -c '^')" == 1 ]] \
    || die "expected one package matching $1, got: ${matches:-none}"
  printf '%s\n' "$matches"
}

# Prove that official OpenWrt repositories of this release satisfy the packages.
# apk 3 turns a simulated write into a read-only operation, so it cannot create
# the database itself: give it an empty world and an empty installed database.
check_dependencies() {
  local apk="$SDK_DIR/staging_dir/host/bin/apk"
  local base="$DOWNLOADS/$release"
  local apk_root="$WORK_DIR/apk-root" kmods
  mkdir -p "$apk_root/etc/apk/cache" "$apk_root/lib/apk/db" "$apk_root/tmp" "$apk_root/var/log"
  : > "$apk_root/etc/apk/world"
  : > "$apk_root/lib/apk/db/installed"
  ln -s /dev/null "$apk_root/var/log/apk.log"

  kmods="$(curl --fail --silent --show-error --location "$base/targets/$TARGET/kmods/" \
    | grep -oE 'href="[0-9][^"/]+/"' | sed -E 's/href="([^"]+)\/"/\1/')"
  [[ "$(printf '%s' "$kmods" | grep -c '^')" == 1 ]] \
    || die "expected one kmods directory, got: ${kmods:-none}"

  timeout 300 "$apk" \
    --root "$apk_root" --arch "$ARCH" --allow-untrusted --no-cache --no-progress --timeout 30 \
    --repository "$base/targets/$TARGET/packages/packages.adb" \
    --repository "$base/targets/$TARGET/kmods/$kmods/packages.adb" \
    --repository "$base/packages/$ARCH/base/packages.adb" \
    --repository "$base/packages/$ARCH/luci/packages.adb" \
    --repository "$base/packages/$ARCH/packages/packages.adb" \
    add --simulate --no-scripts "$RELEASE_DIR"/*.apk
}

WORK_DIR="$(mktemp -d /tmp/openwrt-ziti-build.XXXXXX)"
trap 'rm -rf "$WORK_DIR"' EXIT

SDK_ARCHIVE="$(verified_fetch "$release" "$TARGET" 'openwrt-sdk-[^ ]*\.Linux-x86_64\.tar\.zst' "$CACHE_DIR")"
SDK_DIR="$(unpack_sdk "$SDK_ARCHIVE" "$WORK_DIR")"

FEED_DIR="$WORK_DIR/ziti-openwrt"
git clone --filter=blob:none --quiet https://github.com/openziti/ziti-openwrt.git "$FEED_DIR"
git -C "$FEED_DIR" -c advice.detachedHead=false checkout --quiet --detach "$ZITI_OPENWRT_REV"
[[ "$(git -C "$FEED_DIR" rev-parse HEAD)" == "$ZITI_OPENWRT_REV" ]] || die "ziti-openwrt revision mismatch"

for patch_file in "$ROOT"/patches/ziti-openwrt/*.patch; do
  patch --batch --forward -d "$FEED_DIR" -p1 < "$patch_file"
done

# Exact versions: a stale upstream line must fail here, not ship silently.
set_makefile_value() {
  local makefile="$1" variable="$2" value="$3"
  sed -i "s/^${variable}:=.*/${variable}:=${value}/" "$makefile"
  grep -qx "${variable}:=${value}" "$makefile" || die "could not set $variable in $makefile"
}

STACK_FEED="$WORK_DIR/packages"
cp -R "$ROOT/packages" "$STACK_FEED"
set_makefile_value "$FEED_DIR/package/ziti-edge-tunnel/Makefile" PKG_VERSION "$ZET_VERSION"
set_makefile_value "$FEED_DIR/package/ziti-edge-tunnel/Makefile" PKG_HASH "$ZET_SHA256"
set_makefile_value "$FEED_DIR/package/ziti-edge-tunnel/Makefile" PKG_RELEASE "$PACKAGE_RELEASE"
set_makefile_value "$FEED_DIR/package/luci-app-ziti/Makefile" PKG_RELEASE "$PACKAGE_RELEASE"
set_makefile_value "$STACK_FEED/openwrt-ziti-gateway/Makefile" PKG_RELEASE "$PACKAGE_RELEASE"

# Feed names accept only [A-Za-z0-9_].
printf '\nsrc-link ziti_openwrt %s\nsrc-link ziti_stack %s\n' "$FEED_DIR" "$STACK_FEED" \
  >> "$SDK_DIR/feeds.conf.default"

(
  cd "$SDK_DIR"
  # feeds.conf.default of the verified SDK pins the base and packages revisions.
  ./scripts/feeds update base packages ziti_openwrt ziti_stack
  ./scripts/feeds install ziti-edge-tunnel llhttp stc luci-app-ziti openwrt-ziti-gateway

  strip_sdk_release_package_snapshot

  board="${TARGET%%/*}"
  target_kconfig="${TARGET//\//_}"
  printf '%s\n' \
    "CONFIG_TARGET_${board}=y" \
    "CONFIG_TARGET_${target_kconfig}=y" \
    '# CONFIG_ALL is not set' \
    '# CONFIG_ALL_KMODS is not set' \
    '# CONFIG_ALL_NONSHARED is not set' \
    'CONFIG_PACKAGE_ziti-edge-tunnel=m' \
    'CONFIG_PACKAGE_luci-app-ziti=m' \
    'CONFIG_PACKAGE_openwrt-ziti-gateway=m' \
    > .config
  make defconfig

  grep -qx "CONFIG_TARGET_ARCH_PACKAGES=\"$ARCH\"" .config \
    || die "SDK architecture does not match $ARCH"
  for package in llhttp ziti-edge-tunnel luci-app-ziti openwrt-ziti-gateway; do
    grep -Eq "^CONFIG_PACKAGE_${package}=[my]$" .config || die "$package is not selected"
  done

  make -j"$BUILD_JOBS" \
    package/feeds/ziti_openwrt/ziti-edge-tunnel/compile \
    package/feeds/ziti_openwrt/luci-app-ziti/compile \
    package/feeds/ziti_stack/openwrt-ziti-gateway/compile \
    V=s
)

RELEASE_DIR="$OUT_DIR/$release/$ARCH"
rm -rf "$RELEASE_DIR"
mkdir -p "$RELEASE_DIR"
for pattern in \
  "ziti-edge-tunnel-${ZET_VERSION}-r${PACKAGE_RELEASE}.apk" \
  'llhttp9-*.apk' \
  "luci-app-ziti-*-r${PACKAGE_RELEASE}.apk" \
  "openwrt-ziti-gateway-*-r${PACKAGE_RELEASE}.apk"; do
  cp "$(find_package "$pattern")" "$RELEASE_DIR/"
done
chmod 0644 "$RELEASE_DIR"/*.apk

check_dependencies
printf 'built %s\n' "$RELEASE_DIR"
